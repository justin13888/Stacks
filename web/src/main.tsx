import { QueryClientProvider } from "@tanstack/react-query";
import { createRouter, RouterProvider } from "@tanstack/react-router";
import { StrictMode } from "react";
import { createRoot } from "react-dom/client";
import { ErrorState } from "./components/ui/error-state";
import { createQueryClient } from "./config/query-client";
import { applyInitialTheme } from "./hooks/use-theme";
import { registerServiceWorker } from "./lib/service-worker";
import { routeTree } from "./routeTree.gen"; // generated by `just codegen`
import "./styles/global.css";

// Paint the last theme before React renders, so a reload never flashes.
applyInitialTheme();

const { queryClient, freshness } = createQueryClient({
  // A 401 on any call: re-run the guards, which send the user to sign in.
  onSignedOut: () => void router.invalidate(),
});

const router = createRouter({
  routeTree,
  context: { queryClient, freshness },
  defaultPreload: "intent",
  // Loaders read through TanStack Query, which owns caching.
  defaultPreloadStaleTime: 0,
  defaultErrorComponent: ({ error, reset }) => (
    <ErrorState error={error} onRetry={reset} />
  ),
  scrollRestoration: true,
});

declare module "@tanstack/react-router" {
  interface Register {
    router: typeof router;
  }
}

const rootEl = document.getElementById("root");
if (!rootEl) throw new Error("Root element not found");

createRoot(rootEl).render(
  <StrictMode>
    <QueryClientProvider client={queryClient}>
      <RouterProvider router={router} />
    </QueryClientProvider>
  </StrictMode>,
);

registerServiceWorker();
