import { QueryClientProvider } from "@tanstack/react-query";
import { RouterProvider, createRouter } from "@tanstack/react-router";
import { StrictMode } from "react";
import { createRoot } from "react-dom/client";
import { queryClient } from "./config/query-client";
import { restoreSession } from "./lib/auth";
import { routeTree } from "./routeTree.gen"; // generated by TanStack Router plugin
import "./styles/global.css";

const router = createRouter({ routeTree });

declare module "@tanstack/react-router" {
  interface Register {
    router: typeof router;
  }
}

const rootEl = document.getElementById("root");
if (!rootEl) throw new Error("Root element not found");

// Restore any persisted session *before* mounting. The /_authenticated guard
// reads auth state synchronously in beforeLoad, so mounting first would
// redirect to /login on every reload before the refresh call could land.
restoreSession().finally(() => {
  createRoot(rootEl).render(
    <StrictMode>
      <QueryClientProvider client={queryClient}>
        <RouterProvider router={router} />
      </QueryClientProvider>
    </StrictMode>,
  );
});
